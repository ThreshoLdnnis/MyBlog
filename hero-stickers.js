function createSticker({name, sourceHeight, crop, outline}) {
  const [x, y, width, height] = crop;
  const sticker = document.createElement('span');
  sticker.className = 'hero-sticker';
  sticker.dataset.sticker = name;

  const mask = document.createElement('span');
  mask.className = 'hero-sticker-crop';
  mask.style.setProperty('--crop-ratio', `${width} / ${height}`);
  mask.style.setProperty('--outline', outline);

  const image = document.createElement('img');
  image.alt = '';
  image.loading = 'lazy';
  image.decoding = 'async';
  image.draggable = false;
  Object.assign(image.style, {
    width: `${sheetWidth / width * 100}%`,
    height: `${sourceHeight / height * 100}%`,
    left: `${-x / width * 100}%`,
    top: `${-y / height * 100}%`,
  });
  image.src = `assets/hero/sticker-sheets/${name}.webp`;
  mask.append(image);
  sticker.append(mask);
  return sticker;
}

const limit = value => Math.max(-1, Math.min(1, value));

export function mountHeroStickers(board) {
  const pieces = stickers.map(createSticker);
  board.replaceChildren(...pieces);
  const reduceMotion = matchMedia('(prefers-reduced-motion: reduce)');
  let cursor;
  let frame = 0;

  function movePieces() {
    frame = 0;
    const bounds = board.getBoundingClientRect();
    const x = cursor.x - bounds.left;
    const y = cursor.y - bounds.top;
    const reach = Math.min(155, bounds.width * .58);

    const centers = pieces.map(piece => [piece.offsetLeft, piece.offsetTop]);
    pieces.forEach((piece, index) => {
      const [centerX, centerY] = centers[index];
      const directionX = (centerX - x) / reach;
      const directionY = (centerY - y) / reach;
      const falloff = Math.max(0, 1 - Math.hypot(directionX, directionY));
      const strength = falloff ** 1.4;
      piece.style.setProperty('--wind-x', `${((cursor.horizontal * 7 + directionX * 4) * strength).toFixed(2)}px`);
      piece.style.setProperty('--wind-y', `${((cursor.vertical * 5 + directionY * 3 - 3) * strength).toFixed(2)}px`);
      piece.style.setProperty('--wind-angle', `${((cursor.horizontal * 4 + directionX * 2 + 1) * strength).toFixed(2)}deg`);
    });
  }

  function settle() {
    cancelAnimationFrame(frame);
    frame = 0;
    cursor = undefined;
    for (const piece of pieces) {
      piece.style.removeProperty('--wind-x');
      piece.style.removeProperty('--wind-y');
      piece.style.removeProperty('--wind-angle');
    }
  }

  board.addEventListener('pointermove', event => {
    if (reduceMotion.matches || event.pointerType === 'touch') return;
    const {clientX: x, clientY: y} = event;
    cursor = {
      x,
      y,
      horizontal: limit((x - (cursor?.x ?? x)) / 22),
      vertical: limit((y - (cursor?.y ?? y)) / 22),
    };
    if (!frame) frame = requestAnimationFrame(movePieces);
  });
  board.addEventListener('pointerleave', settle);
  board.addEventListener('pointercancel', settle);
  reduceMotion.addEventListener('change', settle);
}
